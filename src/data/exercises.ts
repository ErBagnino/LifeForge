import type { Exercise, ExerciseCategory, MuscleTarget, ProgressionRule, WorkoutPlan } from '@/types';

const WEIGHT_RULE: ProgressionRule = {
  increment: 2.5,
  maxIncreasePct: 15,
  easyRpeMax: 2,
  requireAllSets: true,
  requireTopOfRange: true,
  failuresBeforeDeload: 3,
  deloadPct: 10,
  minWeight: 0,
};
const SMALL_RULE: ProgressionRule = { ...WEIGHT_RULE, increment: 1, maxIncreasePct: 25 };
const BODYWEIGHT_RULE: ProgressionRule = { ...WEIGHT_RULE, increment: 2 };
const TIME_RULE: ProgressionRule = { ...WEIGHT_RULE, increment: 5 };

type M = [MuscleTarget['muscle'], MuscleTarget['level']];

interface ExOpts {
  category?: ExerciseCategory;
  measure?: Exercise['measure'];
  equipment: string;
  muscles: M[];
  instructions: string[];
  sets?: number;
  reps: [number, number];
  rest?: number;
  difficulty?: Exercise['difficulty'];
  rule?: ProgressionRule;
  illustration?: string;
  unilateral?: boolean;
  bodyweight?: boolean;
  notes?: string;
}

function ex(id: string, name: string, o: ExOpts): Exercise {
  return {
    id,
    name,
    category: o.category ?? 'strength',
    measure: o.measure ?? 'reps',
    muscles: o.muscles.map(([muscle, level]) => ({ muscle, level })),
    equipment: o.equipment,
    instructions: o.instructions,
    defaultSets: o.sets ?? 3,
    repMin: o.reps[0],
    repMax: o.reps[1],
    restSec: o.rest ?? 90,
    difficulty: o.difficulty ?? 3,
    progression: o.rule ?? (o.bodyweight ? BODYWEIGHT_RULE : WEIGHT_RULE),
    illustration: o.illustration ?? id,
    unilateral: o.unilateral,
    bodyweight: o.bodyweight,
    notes: o.notes,
    userCreated: false,
    createdAt: 0,
    updatedAt: 0,
  };
}

